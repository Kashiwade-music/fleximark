//! Role: Verify generated schemas, schema validation and bounds.
use super::*;

#[test]
fn schema_preserves_registry_frame_and_scalar_contracts() {
    let schema: Value =
        serde_json::from_str(&generate_protocol_schema(&named_schemas()).unwrap()).unwrap();
    assert_eq!(schema["$comment"], GENERATED_COMMENT);
    for definition in [
        "customRequest",
        "clientToServerCustomNotification",
        "serverToClientCustomNotification",
        "customNotification",
    ] {
        assert!(
            schema["$defs"][definition]["oneOf"].is_array(),
            "{definition}"
        );
    }
    let encoded = serde_json::to_string(&schema["$defs"]).unwrap();
    for spec in METHOD_SPECS {
        assert!(encoded.contains(spec.name), "{}", spec.name);
    }
    assert!(schema["$defs"]["renderFrame"]["properties"]["blocks"].is_object());
    assert_eq!(
        schema["$defs"]["createPreviewResult"]["required"],
        json!(["frame", "previewSessionId"])
    );
    assert_safe_integer_bounds(&schema);

    assert_eq!(
        schema["$defs"]["renderBlock"]["properties"]["nodeIds"]["uniqueItems"],
        true
    );
    assert_eq!(
        schema["$defs"]["renderBlock"]["properties"]["nodeIds"]["minItems"],
        1
    );
    let create_note = schema["$defs"]["workspaceCommand"]["oneOf"]
        .as_array()
        .unwrap()
        .iter()
        .find(|item| item["properties"]["command"]["const"] == "createNote")
        .unwrap();
    let category_path = &create_note["properties"]["categoryPath"];
    assert_eq!(category_path["type"], "array");
    assert_eq!(category_path["items"]["type"], "string");
    assert_eq!(category_path["items"]["minLength"], 1);
    assert_eq!(category_path["minItems"], 1);
    assert_eq!(category_path["maxItems"], 32);
    let file_name = &create_note["properties"]["name"];
    assert_eq!(file_name["type"], "string");
    assert_eq!(file_name["minLength"], 1);
    assert_eq!(file_name["maxLength"], 255);
}

fn assert_safe_integer_bounds(schema: &Value) {
    match schema {
        Value::Array(items) => items.iter().for_each(assert_safe_integer_bounds),
        Value::Object(object) => {
            if schema_declares_type(object, "integer") {
                let minimum = object["minimum"].as_i64().expect("integer minimum");
                let maximum = object["maximum"].as_i64().expect("integer maximum");
                assert!(minimum >= -MAX_SAFE_INTEGER, "{object:?}");
                assert!(maximum <= MAX_SAFE_INTEGER, "{object:?}");
            }
            object.values().for_each(assert_safe_integer_bounds);
        }
        _ => {}
    }
}

#[test]
fn typescript_uses_schema_definitions_directly() {
    let output = generate_typescript(&named_schemas()).unwrap();
    assert!(output.starts_with("// Generated by fleximark-protocol-codegen; DO NOT EDIT."));
    assert!(output.contains("export const CONTRACT_DEFINITIONS = "));
    assert!(output.contains("export const TYPE_VALIDATORS = "));
    assert!(output.contains("export const REQUEST_VALIDATORS = "));
    assert!(output.contains("export const CLIENT_NOTIFICATION_VALIDATORS = "));
    assert!(output.contains("export const SERVER_NOTIFICATION_VALIDATORS = "));
    assert!(!output.contains("export const CONTRACT_SCHEMA"));
    assert!(output.contains("frame: RenderFrame"));
    assert!(output.contains("level: \"info\" | \"warning\" | \"error\""));
    assert!(output.contains("categoryPath?: Array<string>"));
}

#[test]
fn typed_commands_and_http_contracts_are_generated_from_rust() {
    let named = named_schemas();
    let output = generate_typescript(&named).unwrap();
    let schema: Value = serde_json::from_str(&generate_protocol_schema(&named).unwrap()).unwrap();
    assert!(output.contains("export const COMMAND_DESCRIPTORS = "));
    assert!(output.contains("export type WorkspaceCommandName = typeof COMMAND_DESCRIPTORS"));
    assert!(output.contains("export type LspWorkspaceCommandName = typeof COMMAND_DESCRIPTORS"));
    assert!(!output.contains("ExecuteCommandParams"));
    assert!(!output.contains("GetNoteOptionsParams"));
    assert!(!output.contains("fleximark/getNoteOptions"));
    let variants = schema["$defs"]["workspaceCommand"]["oneOf"]
        .as_array()
        .unwrap();
    assert_eq!(variants.len(), COMMAND_DESCRIPTORS.len());
    for descriptor in COMMAND_DESCRIPTORS {
        assert!(output.contains(descriptor.lsp_command));
        let variant = variants
            .iter()
            .find(|variant| variant["properties"]["command"]["const"] == descriptor.name)
            .unwrap();
        assert_eq!(variant["additionalProperties"], false);
    }
    for definition in [
        "workspaceCommandRequest",
        "commandContext",
        "documentCommandContext",
        "workspaceStateRequest",
        "workspaceStateResult",
        "workspaceUiCommandRequest",
    ] {
        assert!(schema["$defs"][definition].is_object(), "{definition}");
    }
    assert_eq!(
        schema["$defs"]["commandResult"]["oneOf"]
            .as_array()
            .unwrap()
            .len(),
        COMMAND_DESCRIPTORS.len()
    );
}
