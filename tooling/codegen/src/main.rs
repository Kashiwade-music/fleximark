fn rewrite_root_references(schema: &mut Value, schema_name: &str) {
    visit_schema_mut(schema, &mut |object| {
        if object.get("$ref").and_then(Value::as_str) == Some("#") {
            object.insert(
                "$ref".to_owned(),
                Value::String(format!("#/$defs/{schema_name}")),
            );
        }
    });
}

fn schema_ref(wire_type: WireType) -> Value {
    if wire_type == WireType::Unit {
        json!({ "type": "null" })
    } else {
        json!({ "$ref": format!("#/$defs/{}", wire_type.schema_name()) })
    }
}

fn local_ref(reference: &str) -> Result<&str, String> {
    reference
        .strip_prefix("#/$defs/")
        .ok_or_else(|| format!("unsupported schema reference: {reference}"))
}

fn method_variant(base: &str, method: &str, params: Value) -> Value {
    json!({ "allOf": [
        { "$ref": format!("#/$defs/{base}") },
        { "properties": { "method": { "const": method }, "params": params } }
    ] })
}

fn method_variants(
    base: &str,
    kind: MethodKind,
    params: impl Fn(&MethodSpec) -> Option<Value>,
) -> Vec<Value> {
    METHOD_SPECS
        .iter()
        .filter(|spec| spec.kind == kind)
        .filter_map(|spec| params(spec).map(|params| method_variant(base, spec.name, params)))
        .collect()
}

fn request_variants() -> Vec<Value> {
    method_variants("requestBase", MethodKind::Request, |spec| {
        Some(schema_ref(
            spec.client_to_server_params_type.expect("request params"),
        ))
    })
}

fn notification_variants(direction: MethodDirection) -> Vec<Value> {
    method_variants("notificationBase", MethodKind::Notification, |spec| {
        match direction {
            MethodDirection::ClientToServer => spec.client_to_server_params_type,
            MethodDirection::ServerToClient => spec.server_to_client_params_type,
            MethodDirection::Bidirectional => None,
        }
        .map(schema_ref)
    })
}

fn combined_notification_variants() -> Vec<Value> {
    method_variants("notificationBase", MethodKind::Notification, |spec| {
        Some(
            match (
                spec.client_to_server_params_type,
                spec.server_to_client_params_type,
            ) {
                (Some(client), Some(server)) => {
                    json!({ "oneOf": [schema_ref(client), schema_ref(server)] })
                }
                (Some(params), None) | (None, Some(params)) => schema_ref(params),
                (None, None) => json!({ "type": "null" }),
            },
        )
    })
}

fn root_schema(value: &Value) -> Value {
    let mut root = value.clone();
    if let Some(object) = root.as_object_mut() {
        object.remove("$defs");
    }
    root
}

fn shared_definitions(named: &[NamedSchema]) -> Result<Map<String, Value>, String> {
    let mut shared = Map::new();
    for item in named {
        let Some(definitions) = item.value.get("$defs").and_then(Value::as_object) else {
            continue;
        };
        for (name, schema) in definitions {
            if let Some(previous) = shared.get(name) {
                if previous != schema {
                    return Err(format!("conflicting schemars definition: {name}"));
                }
            } else {
                shared.insert(name.clone(), schema.clone());
            }
        }
    }
    apply_semantic_overlays(&mut shared);
    flatten_tagged_variants(&mut shared)?;
    Ok(shared)
}

fn apply_semantic_overlays(definitions: &mut Map<String, Value>) {
    for (schema, property, keyword, value) in [
        (
            "RenderStyle",
            "fingerprint",
            "pattern",
            json!("^[0-9a-f]{64}$"),
        ),
        ("NavigationEntry", "nodeId", "minLength", json!(1)),
    ] {
        if let Some(schema) = definitions.get_mut(schema) {
            schema["properties"][property][keyword] = value;
        }
    }
    if let Some(asset) = definitions.get_mut("RenderAsset") {
        asset["properties"]["reference"]["pattern"] = json!("^fleximark-asset:[0-9a-f]{64}$");
        asset["properties"]["mediaType"] = json!({ "enum": [
            "image/png", "image/jpeg", "image/gif", "image/webp",
            "audio/mpeg", "audio/ogg", "audio/wav"
        ] });
        asset["properties"]["contentHash"]["pattern"] = json!("^[0-9a-f]{64}$");
        asset["properties"]["data"]["contentEncoding"] = json!("base64");
    }
    if let Some(block) = definitions.get_mut("RenderBlock") {
        block["properties"]["nodeIds"]["minItems"] = json!(1);
        block["properties"]["nodeIds"]["uniqueItems"] = json!(true);
        block["properties"]["nodeIds"]["items"]["minLength"] = json!(1);
    }
    for name in ["PreviewNavigationEvent", "RenderNavigationEvent"] {
        if let Some(schema) = definitions.get_mut(name) {
            add_nonempty_node_ids(schema);
        }
    }
    if let Some(options) = definitions.get_mut("GetNoteOptionsResult") {
        options["properties"]["categories"]["uniqueItems"] = json!(true);
        options["properties"]["templates"]["uniqueItems"] = json!(true);
    }
    if let Some(category) = definitions.get_mut("NoteCategoryOption") {
        category["properties"]["name"]["minLength"] = json!(1);
    }
    if let Some(params) = definitions.get_mut("ExecuteCommandParams") {
        let path = &mut params["properties"]["noteCategoryPath"];
        remove_null_variant(path);
        path["minItems"] = json!(1);
        path["maxItems"] = json!(32);
        path["items"]["minLength"] = json!(1);
        let file_name = &mut params["properties"]["noteFileName"];
        remove_null_variant(file_name);
        file_name["minLength"] = json!(1);
        file_name["maxLength"] = json!(255);
    }
}

fn visit_schema_mut(schema: &mut Value, visitor: &mut impl FnMut(&mut Map<String, Value>)) {
    match schema {
        Value::Array(items) => items
            .iter_mut()
            .for_each(|item| visit_schema_mut(item, visitor)),
        Value::Object(object) => {
            visitor(object);
            object
                .values_mut()
                .for_each(|value| visit_schema_mut(value, visitor));
        }
        _ => {}
    }
}

fn add_nonempty_node_ids(schema: &mut Value) {
    visit_schema_mut(schema, &mut |object| {
        if let Some(Value::Object(properties)) = object.get_mut("properties") {
            for (name, value) in properties {
                if matches!(
                    name.as_str(),
                    "nodeId" | "parentId" | "currentParentId" | "previewSessionId"
                ) {
                    value["minLength"] = json!(1);
                } else if matches!(name.as_str(), "nodeIds" | "contentNodeIds") {
                    value["items"]["minLength"] = json!(1);
                    value["uniqueItems"] = json!(true);
                }
            }
        }
    });
}

fn schema_declares_type(object: &Map<String, Value>, expected: &str) -> bool {
    match object.get("type") {
        Some(Value::String(kind)) => kind == expected,
        Some(Value::Array(kinds)) => kinds.iter().any(|kind| kind.as_str() == Some(expected)),
        _ => false,
    }
}

fn flatten_tagged_variants(definitions: &mut Map<String, Value>) -> Result<(), String> {
    let snapshot = definitions.clone();
    for schema in definitions.values_mut() {
        flatten_tagged_schema(schema, &snapshot)?;
    }
    Ok(())
}

fn flatten_tagged_schema(
    schema: &mut Value,
    definitions: &Map<String, Value>,
) -> Result<(), String> {
    match schema {
        Value::Array(items) => {
            for item in items {
                flatten_tagged_schema(item, definitions)?;
            }
        }
        Value::Object(object) => {
            let tagged_reference = object
                .get("$ref")
                .and_then(Value::as_str)
                .zip(object.get("properties").and_then(Value::as_object))
                .filter(|(_, properties)| properties.contains_key("type"))
                .map(|(reference, _)| reference.to_owned());
            if let Some(reference) = tagged_reference {
                let name = local_ref(&reference)?;
                let mut merged = definitions
                    .get(name)
                    .cloned()
                    .ok_or_else(|| format!("missing tagged schema definition: {name}"))?;
                let merged_object = merged
                    .as_object_mut()
                    .ok_or_else(|| format!("tag target is not an object: {name}"))?;
                let tagged_properties = object.get("properties").cloned().unwrap();
                merged_object
                    .get_mut("properties")
                    .and_then(Value::as_object_mut)
                    .expect("tag target has properties")
                    .extend(tagged_properties.as_object().unwrap().clone());
                let mut required = merged_object
                    .remove("required")
                    .and_then(|value| value.as_array().cloned())
                    .unwrap_or_default();
                for field in object
                    .get("required")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                {
                    if !required.contains(field) {
                        required.push(field.clone());
                    }
                }
                merged_object.insert("required".to_owned(), Value::Array(required));
                *schema = merged;
            } else {
                for child in object.values_mut() {
                    flatten_tagged_schema(child, definitions)?;
                }
            }
        }
        _ => {}
    }
    Ok(())
}

fn contract_root(item: &NamedSchema, definitions: &Map<String, Value>) -> Result<Value, String> {
    let mut root = root_schema(&item.value);
    let mut singleton = Map::new();
    singleton.insert(item.ts_name.to_owned(), root);
    apply_semantic_overlays(&mut singleton);
    root = singleton
        .remove(item.ts_name)
        .expect("semantic overlay preserves its root");
    flatten_tagged_schema(&mut root, definitions)?;
    Ok(root)
}

fn generate_protocol_schema(named: &[NamedSchema]) -> Result<String, String> {
    let mut definitions = shared_definitions(named)?;
    definitions.insert("jsonValue".to_owned(), json!({
        "oneOf": [
            { "type": "null" }, { "type": "boolean" }, { "type": "number" }, { "type": "string" },
            { "type": "array", "items": { "$ref": "#/$defs/jsonValue" } },
            { "type": "object", "additionalProperties": { "$ref": "#/$defs/jsonValue" } }
        ]
    }));
    definitions.insert(
        "structuredParams".to_owned(),
        json!({ "oneOf": [
        { "type": "object", "additionalProperties": { "$ref": "#/$defs/jsonValue" } },
        { "type": "array", "items": { "$ref": "#/$defs/jsonValue" } }
    ] }),
    );
    definitions.insert("unit".to_owned(), json!({ "type": "null" }));
    for item in named {
        let root = contract_root(item, &definitions)?;
        if definitions
            .insert(item.schema_name.to_owned(), root)
            .is_some()
        {
            return Err(format!("duplicate schema name: {}", item.schema_name));
        }
    }
    definitions.insert(
        "responseId".to_owned(),
        json!({ "oneOf": [{ "$ref": "#/$defs/id" }, { "type": "null" }] }),
    );
    definitions.insert(
        "clientPreviewEventParams".to_owned(),
        json!({ "$ref": "#/$defs/previewEventParams" }),
    );
    definitions.insert("requestBase".to_owned(), json!({
        "type": "object", "additionalProperties": false,
        "properties": { "jsonrpc": { "const": "2.0" }, "id": { "$ref": "#/$defs/id" }, "method": { "type": "string" }, "params": { "type": "object" } },
        "required": ["jsonrpc", "id", "method", "params"]
    }));
    definitions.insert("notificationBase".to_owned(), json!({
        "type": "object", "additionalProperties": false,
        "properties": { "jsonrpc": { "const": "2.0" }, "method": { "type": "string" }, "params": { "type": "object" } },
        "required": ["jsonrpc", "method", "params"]
    }));
    definitions.insert(
        "customRequest".to_owned(),
        json!({ "oneOf": request_variants() }),
    );
    definitions.insert(
        "clientToServerCustomNotification".to_owned(),
        json!({ "oneOf": notification_variants(MethodDirection::ClientToServer) }),
    );
    definitions.insert(
        "serverToClientCustomNotification".to_owned(),
        json!({ "oneOf": notification_variants(MethodDirection::ServerToClient) }),
    );
    definitions.insert(
        "customNotification".to_owned(),
        json!({ "oneOf": combined_notification_variants() }),
    );
    definitions.insert("diagnostic".to_owned(), diagnostic_schema());
    definitions.insert("publishDiagnosticsParams".to_owned(), json!({
        "type": "object", "additionalProperties": false,
        "properties": { "uri": { "type": "string" }, "version": { "type": "integer" }, "diagnostics": { "type": "array", "items": { "$ref": "#/$defs/diagnostic" } } },
        "required": ["uri", "diagnostics"]
    }));
    definitions.insert("lspMessage".to_owned(), lsp_message_schema());
    definitions.insert("response".to_owned(), response_schema());
    let mut result_properties = Map::new();
    for spec in METHOD_SPECS {
        if spec.name != fleximark_protocol::method::REQUEST_FULL_TEXT {
            result_properties.insert(
                spec.name.to_owned(),
                spec.result_type
                    .map_or_else(|| json!({ "type": "null" }), schema_ref),
            );
        }
    }
    definitions.insert(
        "methodResults".to_owned(),
        json!({
            "type": "object", "description": "Named result DTOs for every FlexiMark method.",
            "properties": result_properties, "additionalProperties": false
        }),
    );

    let mut document = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://fleximark.dev/schemas/protocol-v{PROTOCOL_VERSION}.json"),
        "$comment": GENERATED_COMMENT,
        "title": format!("FlexiMark JSON-RPC protocol v{PROTOCOL_VERSION}"),
        "oneOf": [
            { "$ref": "#/$defs/customRequest" }, { "$ref": "#/$defs/customNotification" },
            { "$ref": "#/$defs/lspMessage" }, { "$ref": "#/$defs/response" }
        ],
        "$defs": definitions
    });
    normalize_schema(&mut document, None);
    serde_json::to_string(&document)
        .map(|mut text| {
            text.push('\n');
            text
        })
        .map_err(|error| error.to_string())
}

