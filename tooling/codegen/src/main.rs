//! Role: Generate schemas and TypeScript from the current Rust wire contract.
mod configuration;
mod distribution;
mod examples;
mod typescript;
use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use typescript::schema_to_typescript;

use fleximark_protocol::{
    COMMAND_DESCRIPTORS, LSP_METHODS, MAX_SAFE_INTEGER, METHOD_SPECS, MethodDirection, MethodKind,
    MethodSpec, PROTOCOL_VERSION, WIRE_TYPES, wire_type,
};
use serde_json::{Map, Value, json};

const GENERATED_COMMENT: &str = "Generated by fleximark-protocol-codegen; DO NOT EDIT.";
const SCHEMA_PATH: &str = "contracts/schemas/protocol.schema.json";
const TYPESCRIPT_PATH: &str = "contracts/typescript/protocol.generated.mts";
struct NamedSchema {
    schema_name: &'static str,
    ts_name: &'static str,
    value: Value,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("{error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let mut arguments = env::args().skip(1);
    let command = arguments.next().ok_or_else(usage)?;
    if arguments.next().is_some() || !matches!(command.as_str(), "generate" | "check") {
        return Err(usage());
    }
    let working = env::current_dir().map_err(|error| error.to_string())?;
    let root = working
        .ancestors()
        .find(|path| path.join("release.toml").is_file() && path.join("Cargo.toml").is_file())
        .ok_or_else(|| "run codegen inside the FlexiMark repository".to_owned())?
        .to_path_buf();
    let named = named_schemas()?;
    let mut outputs = vec![
        (
            root.join("contracts/schemas/config.schema.json"),
            configuration::schema()?,
        ),
        (root.join(SCHEMA_PATH), generate_protocol_schema(&named)?),
        (root.join(TYPESCRIPT_PATH), generate_typescript(&named)?),
    ];
    outputs.extend(examples::outputs(&root)?);
    outputs.extend(distribution::outputs(&root)?);
    if command == "generate" {
        for (path, contents) in outputs {
            fs::write(&path, contents)
                .map_err(|error| format!("failed to write {}: {error}", path.display()))?;
            println!(
                "generated {}",
                path.strip_prefix(&root)
                    .map_err(|error| error.to_string())?
                    .display()
            );
        }
    } else {
        let stale = outputs
            .into_iter()
            .filter_map(|(path, expected)| {
                (fs::read_to_string(&path).ok().as_deref() != Some(&expected)).then_some(path)
            })
            .collect::<Vec<_>>();
        if !stale.is_empty() {
            let paths = stale
                .iter()
                .map(|path| path.display().to_string())
                .collect::<Vec<_>>()
                .join(", ");
            return Err(format!(
                "generated protocol contracts are stale: {paths}; run `cargo run -p fleximark-protocol-codegen -- generate`"
            ));
        }
        println!("generated protocol contracts are current");
    }
    Ok(())
}

fn usage() -> String {
    "usage: fleximark-protocol-codegen <generate|check>".to_owned()
}

fn normalize_schema(value: &mut Value) {
    match value {
        Value::Array(items) => items.iter_mut().for_each(normalize_schema),
        Value::Object(object) => {
            if schema_declares_type(object, "integer") {
                if object
                    .get("minimum")
                    .and_then(Value::as_i64)
                    .is_none_or(|minimum| minimum < -MAX_SAFE_INTEGER)
                {
                    object.insert("minimum".to_owned(), json!(-MAX_SAFE_INTEGER));
                }
                if object
                    .get("maximum")
                    .and_then(Value::as_i64)
                    .is_none_or(|maximum| maximum > MAX_SAFE_INTEGER)
                {
                    object.insert("maximum".to_owned(), json!(MAX_SAFE_INTEGER));
                }
            }
            if object.get("type") == Some(&Value::String("object".to_owned()))
                && object.contains_key("properties")
            {
                object
                    .entry("additionalProperties")
                    .or_insert(Value::Bool(false));
            }
            if let Some(Value::Object(properties)) = object.get_mut("properties") {
                for schema in properties.values_mut() {
                    normalize_schema(schema);
                }
            }
            if let Some(Value::Object(definitions)) = object.get_mut("$defs") {
                for schema in definitions.values_mut() {
                    normalize_schema(schema);
                }
            }
            for key in ["items", "additionalProperties", "not", "if", "then", "else"] {
                if let Some(child) = object.get_mut(key) {
                    normalize_schema(child);
                }
            }
            for key in ["oneOf", "anyOf", "allOf"] {
                if let Some(Value::Array(children)) = object.get_mut(key) {
                    children.iter_mut().for_each(normalize_schema);
                }
            }
        }
        _ => {}
    }
}

fn named_schemas() -> Result<Vec<NamedSchema>, String> {
    let mut schemas = Vec::new();
    for descriptor in WIRE_TYPES
        .iter()
        .filter(|descriptor| descriptor.wire_name != "Unit")
    {
        let mut value = (descriptor.schema)(descriptor.contract)?;
        if let Some(object) = value.as_object_mut() {
            for key in ["$schema", "title", "description"] {
                object.remove(key);
            }
        }
        normalize_schema(&mut value);
        let mut item = NamedSchema {
            schema_name: descriptor.schema_name,
            ts_name: descriptor.typescript_name,
            value,
        };
        rewrite_root_references(&mut item.value, item.schema_name);
        schemas.push(item);
    }
    Ok(schemas)
}

fn rewrite_root_references(schema: &mut Value, schema_name: &str) {
    visit_schema_mut(schema, &mut |object| {
        if object.get("$ref").and_then(Value::as_str) == Some("#") {
            object.insert(
                "$ref".to_owned(),
                Value::String(format!("#/$defs/{schema_name}")),
            );
        }
    });
}

fn schema_ref(wire_key: &str) -> Result<Value, String> {
    if wire_key == "Unit" {
        Ok(json!({ "type": "null" }))
    } else {
        Ok(json!({ "$ref": format!("#/$defs/{}", wire_type(wire_key)?.schema_name) }))
    }
}

fn local_ref(reference: &str) -> Result<&str, String> {
    reference
        .strip_prefix("#/$defs/")
        .ok_or_else(|| format!("unsupported schema reference: {reference}"))
}

fn method_variant(base: &str, method: &str, params: Value) -> Value {
    json!({ "allOf": [
        { "$ref": format!("#/$defs/{base}") },
        { "properties": { "method": { "const": method }, "params": params } }
    ] })
}

fn method_variants(
    base: &str,
    kind: MethodKind,
    params: impl Fn(&MethodSpec) -> Result<Option<Value>, String>,
) -> Result<Vec<Value>, String> {
    let mut variants = Vec::new();
    for spec in METHOD_SPECS.iter().filter(|spec| spec.kind == kind) {
        if let Some(params) = params(spec)? {
            variants.push(method_variant(base, spec.name, params));
        }
    }
    Ok(variants)
}
fn request_variants() -> Result<Vec<Value>, String> {
    method_variants("requestBase", MethodKind::Request, |spec| {
        let params = spec
            .client_to_server_params_type
            .ok_or_else(|| format!("request lacks params: {}", spec.name))?;
        Ok(Some(schema_ref(params)?))
    })
}
fn notification_variants(direction: MethodDirection) -> Result<Vec<Value>, String> {
    method_variants("notificationBase", MethodKind::Notification, |spec| {
        let params = match direction {
            MethodDirection::ClientToServer => spec.client_to_server_params_type,
            MethodDirection::ServerToClient => spec.server_to_client_params_type,
            MethodDirection::Bidirectional => None,
        };
        params.map(schema_ref).transpose()
    })
}
fn combined_notification_variants() -> Result<Vec<Value>, String> {
    method_variants("notificationBase", MethodKind::Notification, |spec| {
        let value = match (
            spec.client_to_server_params_type,
            spec.server_to_client_params_type,
        ) {
            (Some(client), Some(server)) => {
                json!({"oneOf":[schema_ref(client)?,schema_ref(server)?]})
            }
            (Some(params), None) | (None, Some(params)) => schema_ref(params)?,
            (None, None) => json!({"type":"null"}),
        };
        Ok(Some(value))
    })
}

fn root_schema(value: &Value) -> Value {
    let mut root = value.clone();
    if let Some(object) = root.as_object_mut() {
        object.remove("$defs");
    }
    root
}

fn shared_definitions(named: &[NamedSchema]) -> Result<Map<String, Value>, String> {
    let mut shared = Map::new();
    for item in named {
        let Some(definitions) = item.value.get("$defs").and_then(Value::as_object) else {
            continue;
        };
        for (name, schema) in definitions {
            if let Some(previous) = shared.get(name) {
                if previous != schema {
                    return Err(format!("conflicting schemars definition: {name}"));
                }
            } else {
                shared.insert(name.clone(), schema.clone());
            }
        }
    }
    flatten_tagged_variants(&mut shared)?;
    Ok(shared)
}

fn visit_schema_mut(schema: &mut Value, visitor: &mut impl FnMut(&mut Map<String, Value>)) {
    match schema {
        Value::Array(items) => items
            .iter_mut()
            .for_each(|item| visit_schema_mut(item, visitor)),
        Value::Object(object) => {
            visitor(object);
            object
                .values_mut()
                .for_each(|value| visit_schema_mut(value, visitor));
        }
        _ => {}
    }
}

fn schema_declares_type(object: &Map<String, Value>, expected: &str) -> bool {
    match object.get("type") {
        Some(Value::String(kind)) => kind == expected,
        Some(Value::Array(kinds)) => kinds.iter().any(|kind| kind.as_str() == Some(expected)),
        _ => false,
    }
}

fn flatten_tagged_variants(definitions: &mut Map<String, Value>) -> Result<(), String> {
    let snapshot = definitions.clone();
    for schema in definitions.values_mut() {
        flatten_tagged_schema(schema, &snapshot)?;
    }
    Ok(())
}

fn flatten_tagged_schema(
    schema: &mut Value,
    definitions: &Map<String, Value>,
) -> Result<(), String> {
    match schema {
        Value::Array(items) => {
            for item in items {
                flatten_tagged_schema(item, definitions)?;
            }
        }
        Value::Object(object) => {
            let tagged_reference = object
                .get("$ref")
                .and_then(Value::as_str)
                .zip(object.get("properties").and_then(Value::as_object))
                .filter(|(_, properties)| properties.contains_key("type"))
                .map(|(reference, _)| reference.to_owned());
            if let Some(reference) = tagged_reference {
                let name = local_ref(&reference)?;
                let mut merged = definitions
                    .get(name)
                    .cloned()
                    .ok_or_else(|| format!("missing tagged schema definition: {name}"))?;
                let merged_object = merged
                    .as_object_mut()
                    .ok_or_else(|| format!("tag target is not an object: {name}"))?;
                let tagged_properties = object
                    .get("properties")
                    .and_then(Value::as_object)
                    .cloned()
                    .ok_or_else(|| "tag has no properties".to_owned())?;
                merged_object
                    .get_mut("properties")
                    .and_then(Value::as_object_mut)
                    .ok_or_else(|| format!("tag target lacks properties: {name}"))?
                    .extend(tagged_properties);
                let mut required = merged_object
                    .remove("required")
                    .and_then(|value| value.as_array().cloned())
                    .unwrap_or_default();
                for field in object
                    .get("required")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                {
                    if !required.contains(field) {
                        required.push(field.clone());
                    }
                }
                merged_object.insert("required".to_owned(), Value::Array(required));
                *schema = merged;
            } else {
                for child in object.values_mut() {
                    flatten_tagged_schema(child, definitions)?;
                }
            }
        }
        _ => {}
    }
    Ok(())
}

fn contract_root(item: &NamedSchema, definitions: &Map<String, Value>) -> Result<Value, String> {
    let mut root = root_schema(&item.value);
    flatten_tagged_schema(&mut root, definitions)?;
    Ok(root)
}

fn generate_protocol_schema(named: &[NamedSchema]) -> Result<String, String> {
    let mut definitions = shared_definitions(named)?;
    definitions.insert("jsonValue".to_owned(), json!({
        "oneOf": [
            { "type": "null" }, { "type": "boolean" }, { "type": "number" }, { "type": "string" },
            { "type": "array", "items": { "$ref": "#/$defs/jsonValue" } },
            { "type": "object", "additionalProperties": { "$ref": "#/$defs/jsonValue" } }
        ]
    }));
    definitions.insert(
        "structuredParams".to_owned(),
        json!({ "oneOf": [
        { "type": "object", "additionalProperties": { "$ref": "#/$defs/jsonValue" } },
        { "type": "array", "items": { "$ref": "#/$defs/jsonValue" } }
    ] }),
    );
    definitions.insert("unit".to_owned(), json!({ "type": "null" }));
    for item in named {
        let root = contract_root(item, &definitions)?;
        if definitions
            .insert(item.schema_name.to_owned(), root)
            .is_some()
        {
            return Err(format!("duplicate schema name: {}", item.schema_name));
        }
    }
    definitions.insert(
        "responseId".to_owned(),
        json!({ "oneOf": [{ "$ref": "#/$defs/id" }, { "type": "null" }] }),
    );
    definitions.insert(
        "clientPreviewEventParams".to_owned(),
        json!({ "$ref": "#/$defs/previewEventParams" }),
    );
    definitions.insert("requestBase".to_owned(), json!({
        "type": "object", "additionalProperties": false,
        "properties": { "jsonrpc": { "const": "2.0" }, "id": { "$ref": "#/$defs/id" }, "method": { "type": "string" }, "params": { "type": "object" } },
        "required": ["jsonrpc", "id", "method", "params"]
    }));
    definitions.insert("notificationBase".to_owned(), json!({
        "type": "object", "additionalProperties": false,
        "properties": { "jsonrpc": { "const": "2.0" }, "method": { "type": "string" }, "params": { "type": "object" } },
        "required": ["jsonrpc", "method", "params"]
    }));
    definitions.insert(
        "customRequest".to_owned(),
        json!({ "oneOf": request_variants()? }),
    );
    definitions.insert(
        "clientToServerCustomNotification".to_owned(),
        json!({ "oneOf": notification_variants(MethodDirection::ClientToServer)? }),
    );
    definitions.insert(
        "serverToClientCustomNotification".to_owned(),
        json!({ "oneOf": notification_variants(MethodDirection::ServerToClient)? }),
    );
    definitions.insert(
        "customNotification".to_owned(),
        json!({ "oneOf": combined_notification_variants()? }),
    );
    definitions.insert("diagnostic".to_owned(), diagnostic_schema());
    definitions.insert("publishDiagnosticsParams".to_owned(), json!({
        "type": "object", "additionalProperties": false,
        "properties": { "uri": { "type": "string" }, "version": { "type": "integer" }, "diagnostics": { "type": "array", "items": { "$ref": "#/$defs/diagnostic" } } },
        "required": ["uri", "diagnostics"]
    }));
    definitions.insert("lspMessage".to_owned(), lsp_message_schema()?);
    definitions.insert("response".to_owned(), response_schema());
    let mut result_properties = Map::new();
    for spec in METHOD_SPECS {
        {
            result_properties.insert(
                spec.name.to_owned(),
                schema_ref(spec.result_type.unwrap_or("Unit"))?,
            );
        }
    }
    definitions.insert(
        "methodResults".to_owned(),
        json!({
            "type": "object", "description": "Named result DTOs for every FlexiMark method.",
            "properties": result_properties, "additionalProperties": false
        }),
    );

    let mut document = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://fleximark.dev/schemas/protocol-v{PROTOCOL_VERSION}.json"),
        "$comment": GENERATED_COMMENT,
        "title": format!("FlexiMark JSON-RPC protocol v{PROTOCOL_VERSION}"),
        "oneOf": [
            { "$ref": "#/$defs/customRequest" }, { "$ref": "#/$defs/customNotification" },
            { "$ref": "#/$defs/lspMessage" }, { "$ref": "#/$defs/response" }
        ],
        "$defs": definitions
    });
    normalize_schema(&mut document);
    serde_json::to_string(&document)
        .map(|mut text| {
            text.push('\n');
            text
        })
        .map_err(|error| error.to_string())
}

fn diagnostic_schema() -> Value {
    json!({
        "type": "object", "additionalProperties": false,
        "properties": {
            "range": { "$ref": "#/$defs/range" }, "severity": { "type": "integer" }, "code": { "type": ["integer", "string"] },
            "codeDescription": { "type": "object", "additionalProperties": false, "properties": { "href": { "type": "string" } }, "required": ["href"] },
            "source": { "type": "string" }, "message": { "type": "string" }, "tags": { "type": "array", "items": { "type": "integer" } },
            "relatedInformation": { "type": "array", "items": { "type": "object", "additionalProperties": false,
                "properties": { "location": { "type": "object", "additionalProperties": false,
                    "properties": { "uri": { "type": "string" }, "range": { "$ref": "#/$defs/range" } }, "required": ["uri", "range"] },
                    "message": { "type": "string" } }, "required": ["location", "message"] } },
            "data": { "$ref": "#/$defs/jsonValue" }
        }, "required": ["range", "message"]
    })
}

fn lsp_message_schema() -> Result<Value, String> {
    let methods = LSP_METHODS.iter().map(|spec| spec.name).collect::<Vec<_>>();
    let mut constraints = vec![
        json!({ "if": { "properties": { "method": { "const": "textDocument/publishDiagnostics" } }, "required": ["method"] },
            "then": { "properties": { "params": { "$ref": "#/$defs/publishDiagnosticsParams" } }, "required": ["params"] } }),
    ];
    for spec in LSP_METHODS {
        if let Some(key) = spec.params {
            constraints.push(json!({"if":{"properties":{"method":{"const":spec.name}},"required":["method"]},"then":{"properties":{"params":schema_ref(key)?},"required":["params"]}}));
        }
    }
    Ok(json!({
        "type": "object", "additionalProperties": false,
        "properties": { "jsonrpc": { "const": "2.0" }, "id": { "$ref": "#/$defs/id" }, "method": { "enum": methods }, "params": { "$ref": "#/$defs/structuredParams" } },
        "required": ["jsonrpc", "method"], "allOf": constraints
    }))
}

fn response_schema() -> Value {
    json!({
        "type": "object", "additionalProperties": false,
        "properties": {
            "jsonrpc": { "const": "2.0" }, "id": { "$ref": "#/$defs/responseId" }, "result": { "$ref": "#/$defs/jsonValue" },
            "error": { "type": "object", "additionalProperties": false,
                "properties": { "code": { "type": "integer" }, "message": { "type": "string" }, "data": { "$ref": "#/$defs/jsonValue" } },
                "required": ["code", "message"] }
        }, "required": ["jsonrpc", "id"], "oneOf": [{ "required": ["result"] }, { "required": ["error"] }]
    })
}

fn generate_typescript(named: &[NamedSchema]) -> Result<String, String> {
    let mut output = format!("// {GENERATED_COMMENT}\n\n");
    output.push_str(&format!(
        "export const PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\n\n"
    ));
    output.push_str(&format!(
        "export const COMMAND_DESCRIPTORS = {} as const;\n\n",
        serde_json::to_string_pretty(COMMAND_DESCRIPTORS).map_err(|error| error.to_string())?
    ));
    write_json_const(
        &mut output,
        "SEMANTIC_TOKEN_TYPES",
        &fleximark_protocol::SEMANTIC_TOKEN_TYPES,
    )?;
    write_json_const(
        &mut output,
        "SEMANTIC_TOKEN_MODIFIERS",
        &fleximark_protocol::SEMANTIC_TOKEN_MODIFIERS,
    )?;
    output.push_str("export interface WireTypeMap {\n");
    for descriptor in WIRE_TYPES {
        output.push_str(&format!(
            "  {}: {};\n",
            descriptor.schema_name, descriptor.typescript_name
        ));
    }
    output.push_str("}\n\n");
    output.push_str("export type WorkspaceCommandName = typeof COMMAND_DESCRIPTORS[number][\"name\"];\nexport type LspWorkspaceCommandName = typeof COMMAND_DESCRIPTORS[number][\"lspCommand\"];\n\n");
    let command_kinds = COMMAND_DESCRIPTORS
        .iter()
        .map(|descriptor| (descriptor.name, descriptor.name))
        .collect::<BTreeMap<_, _>>();
    write_json_const(&mut output, "WORKSPACE_COMMAND_KIND", &command_kinds)?;
    let shared = shared_definitions(named)?;
    let mut exported = BTreeMap::new();
    for item in named {
        exported.insert(item.ts_name, item.ts_name);
        exported.insert(item.schema_name, item.ts_name);
    }
    for item in named {
        let root = contract_root(item, &shared)?;
        let schema = expand_type_refs(&root, &shared, &exported, false, &mut BTreeSet::new())?;
        output.push_str(&format!(
            "export type {} = {};\n\n",
            item.ts_name,
            schema_to_typescript(&schema)?
        ));
    }
    write_typescript_map(&mut output, "CustomRequestMap", |spec| {
        if spec.kind != MethodKind::Request {
            return Ok(None);
        }
        let params = wire_type(
            spec.client_to_server_params_type
                .ok_or_else(|| format!("request lacks params: {}", spec.name))?,
        )?
        .typescript_name;
        let result = wire_type(spec.result_type.unwrap_or("Unit"))?.typescript_name;
        Ok(Some(format!("{{ params: {params}; result: {result} }}")))
    })?;
    write_typescript_map(&mut output, "ClientNotificationMap", |spec| {
        if spec.kind != MethodKind::Notification {
            return Ok(None);
        }
        spec.client_to_server_params_type
            .map(|key| wire_type(key).map(|descriptor| descriptor.typescript_name.to_owned()))
            .transpose()
    })?;
    write_typescript_map(&mut output, "FleximarkServerNotificationMap", |spec| {
        if spec.kind != MethodKind::Notification {
            return Ok(None);
        }
        spec.server_to_client_params_type
            .map(|key| wire_type(key).map(|descriptor| descriptor.typescript_name.to_owned()))
            .transpose()
    })?;

    let mut contract_definitions = shared;
    contract_definitions.insert("unit".to_owned(), json!({ "type": "null" }));
    let mut validator_roots = Map::new();
    validator_roots.insert("unit".to_owned(), json!({ "type": "null" }));
    for item in named {
        let root = contract_root(item, &contract_definitions)?;
        contract_definitions.insert(item.schema_name.to_owned(), root.clone());
        validator_roots.insert(item.schema_name.to_owned(), root);
    }
    let type_validators = validator_roots
        .keys()
        .map(|name| {
            let semantic = WIRE_TYPES
                .iter()
                .find(|descriptor| descriptor.schema_name == name)
                .and_then(|descriptor| descriptor.semantic);
            (name.clone(), json!({"schema":name,"semantic":semantic}))
        })
        .collect::<Map<_, _>>();
    write_json_const(&mut output, "CONTRACT_DEFINITIONS", &contract_definitions)?;
    write_json_const(&mut output, "TYPE_VALIDATORS", &type_validators)?;
    let (requests, client_notifications, server_notifications) =
        method_validator_schemas(&type_validators)?;
    for (name, value) in &[
        ("REQUEST_VALIDATORS", requests),
        ("CLIENT_NOTIFICATION_VALIDATORS", client_notifications),
        ("SERVER_NOTIFICATION_VALIDATORS", server_notifications),
    ] {
        write_json_const(&mut output, name, value)?;
    }
    output.push_str("export const WIRE_SCHEMAS = {\n");
    let mut wire_types = WIRE_TYPES.to_vec();
    wire_types.sort_by_key(|wire_type| wire_type.wire_name);
    for wire_type in wire_types {
        output.push_str(&format!(
            "  {:?}: {:?},\n",
            wire_type.wire_name, wire_type.schema_name
        ));
    }
    output.push_str("} as const;\n\nexport const METHOD_SPECS = [\n");
    for spec in METHOD_SPECS {
        output.push_str(&format!(
            "  {{ name: {:?}, direction: {:?}, kind: {:?}, clientToServerParamsType: {}, serverToClientParamsType: {}, resultType: {} }},\n",
            spec.name, direction_name(spec.direction), kind_name(spec.kind),
            option_wire_name(spec.client_to_server_params_type), option_wire_name(spec.server_to_client_params_type), option_wire_name(spec.result_type),
        ));
    }
    output.push_str("] as const;\n");
    Ok(output)
}

fn write_typescript_map(
    output: &mut String,
    name: &str,
    entry: impl Fn(&MethodSpec) -> Result<Option<String>, String>,
) -> Result<(), String> {
    output.push_str(&format!("export interface {name} {{\n"));
    for spec in METHOD_SPECS {
        if let Some(value) = entry(spec)? {
            output.push_str(&format!("  {:?}: {value};\n", spec.name));
        }
    }
    output.push_str("}\n\n");
    Ok(())
}

fn write_json_const<T: serde::Serialize>(
    output: &mut String,
    name: &str,
    value: &T,
) -> Result<(), String> {
    output.push_str(&format!("export const {name} = "));
    output.push_str(&serde_json::to_string(value).map_err(|error| error.to_string())?);
    output.push_str(" as const;\n\n");
    Ok(())
}

type MethodValidatorSchemas = (Map<String, Value>, Map<String, Value>, Map<String, Value>);

fn method_validator_schemas(
    type_validators: &Map<String, Value>,
) -> Result<MethodValidatorSchemas, String> {
    let index = |wire_key: &str| -> Result<Value, String> {
        let name = wire_type(wire_key)?.schema_name;
        type_validators
            .get(name)
            .cloned()
            .ok_or_else(|| format!("missing validator root: {name}"))
    };
    let mut requests = Map::new();
    let mut client_notifications = Map::new();
    let mut server_notifications = Map::new();
    for spec in METHOD_SPECS {
        if spec.kind == MethodKind::Request {
            let params = spec
                .client_to_server_params_type
                .ok_or_else(|| format!("request lacks params: {}", spec.name))?;
            let result = spec.result_type.unwrap_or("Unit");
            requests.insert(
                spec.name.to_owned(),
                json!([index(params)?, index(result)?]),
            );
        } else {
            if let Some(params) = spec.client_to_server_params_type {
                client_notifications.insert(spec.name.to_owned(), json!(index(params)?));
            }
            if let Some(params) = spec.server_to_client_params_type {
                server_notifications.insert(spec.name.to_owned(), json!(index(params)?));
            }
        }
    }
    Ok((requests, client_notifications, server_notifications))
}

fn expand_type_refs(
    schema: &Value,
    definitions: &Map<String, Value>,
    exported: &BTreeMap<&str, &str>,
    preserve_exported: bool,
    stack: &mut BTreeSet<String>,
) -> Result<Value, String> {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let name = local_ref(reference)?;
        if preserve_exported {
            if let Some(ts_name) = exported.get(name) {
                return Ok(json!({ "x-typescript-ref": ts_name }));
            }
        }
        if !stack.insert(name.to_owned()) {
            return Ok(json!({ "x-typescript-ref": name }));
        }
        let target = definitions
            .get(name)
            .ok_or_else(|| format!("missing schema definition: {name}"))?;
        let expanded = expand_type_refs(target, definitions, exported, true, stack)?;
        stack.remove(name);
        return Ok(expanded);
    }
    let mut expanded = schema.clone();
    match &mut expanded {
        Value::Array(items) => {
            for item in items {
                *item = expand_type_refs(item, definitions, exported, true, stack)?;
            }
        }
        Value::Object(object) => {
            object.remove("$defs");
            for value in object.values_mut() {
                *value = expand_type_refs(value, definitions, exported, true, stack)?;
            }
        }
        _ => {}
    }
    Ok(expanded)
}

fn option_wire_name(value: Option<&str>) -> String {
    value.map_or_else(|| "null".to_owned(), |wire_type| format!("{wire_type:?}"))
}

fn direction_name(direction: MethodDirection) -> &'static str {
    match direction {
        MethodDirection::ClientToServer => "clientToServer",
        MethodDirection::ServerToClient => "serverToClient",
        MethodDirection::Bidirectional => "bidirectional",
    }
}

fn kind_name(kind: MethodKind) -> &'static str {
    match kind {
        MethodKind::Request => "request",
        MethodKind::Notification => "notification",
    }
}

