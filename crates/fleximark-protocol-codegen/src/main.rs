fn main() {
    if let Err(error) = run() {
        eprintln!("{error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let mut arguments = env::args().skip(1);
    let command = arguments.next().ok_or_else(usage)?;
    if arguments.next().is_some() || !matches!(command.as_str(), "generate" | "check") {
        return Err(usage());
    }
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("codegen crate is directly under the workspace")
        .to_owned();
    let named = named_schemas();
    let outputs = [
        (root.join(SCHEMA_PATH), generate_protocol_schema(&named)?),
        (root.join(TYPESCRIPT_PATH), generate_typescript(&named)?),
        (
            root.join(RUST_RENDER_FRAME_FIXTURE_PATH),
            generate_render_frame_fixture()?,
        ),
    ];
    if command == "generate" {
        for (path, contents) in outputs {
            fs::write(&path, contents)
                .map_err(|error| format!("failed to write {}: {error}", path.display()))?;
            println!("generated {}", path.strip_prefix(&root).unwrap().display());
        }
    } else {
        let stale = outputs
            .into_iter()
            .filter_map(|(path, expected)| {
                (fs::read_to_string(&path).ok().as_deref() != Some(&expected)).then_some(path)
            })
            .collect::<Vec<_>>();
        if !stale.is_empty() {
            let paths = stale
                .iter()
                .map(|path| path.strip_prefix(&root).unwrap().display().to_string())
                .collect::<Vec<_>>()
                .join(", ");
            return Err(format!(
                "generated protocol contracts are stale: {paths}; run `cargo run -p fleximark-protocol-codegen -- generate`"
            ));
        }
        println!("generated protocol contracts are current");
    }
    Ok(())
}

fn generate_render_frame_fixture() -> Result<String, String> {
    let mut session = DocumentSession::open(
        DocumentUri("file:///rust-render-frame-fixture.md".to_owned()),
        7,
        "# Rust render frame\n\nGenerated by the engine.\n".to_owned(),
        PositionEncoding::Utf8,
    )
    .map_err(|error| format!("failed to open render-frame fixture: {error}"))?;
    let frame = session
        .render(
            PreviewSessionId("rust-render-frame-fixture".to_owned()),
            &RenderContext::default(),
        )
        .map_err(|error| format!("failed to render frame fixture: {error}"))?;
    serde_json::to_string_pretty(&frame)
        .map(|json| format!("{json}\n"))
        .map_err(|error| format!("failed to serialize render-frame fixture: {error}"))
}

