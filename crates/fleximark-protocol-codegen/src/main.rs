fn generate_typescript(named: &[NamedSchema]) -> Result<String, String> {
    let mut output = format!("// {GENERATED_COMMENT}\n\n");
    output.push_str(&format!(
        "export const PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\n\n"
    ));
    let shared = shared_definitions(named)?;
    let mut exported = BTreeMap::new();
    for item in named {
        exported.insert(item.ts_name, item.ts_name);
        exported.insert(item.schema_name, item.ts_name);
    }
    for item in named {
        let root = contract_root(item, &shared)?;
        let schema = expand_type_refs(&root, &shared, &exported, false, &mut BTreeSet::new())?;
        output.push_str(&format!(
            "export type {} = {};\n\n",
            item.ts_name,
            schema_to_typescript(&schema)?
        ));
    }
    write_typescript_map(&mut output, "CustomRequestMap", |spec| {
        (spec.kind == MethodKind::Request).then(|| {
            let params = spec
                .client_to_server_params_type
                .expect("request params")
                .typescript_name();
            let result = spec.result_type.unwrap_or(WireType::Unit).typescript_name();
            format!("{{ params: {params}; result: {result} }}")
        })
    });
    write_typescript_map(&mut output, "ClientNotificationMap", |spec| {
        (spec.kind == MethodKind::Notification)
            .then_some(spec.client_to_server_params_type)
            .flatten()
            .map(|params| params.typescript_name().to_owned())
    });
    write_typescript_map(&mut output, "FleximarkServerNotificationMap", |spec| {
        (spec.kind == MethodKind::Notification)
            .then_some(spec.server_to_client_params_type)
            .flatten()
            .map(|params| params.typescript_name().to_owned())
    });

    let mut contract_definitions = shared;
    contract_definitions.insert("unit".to_owned(), json!({ "type": "null" }));
    let mut validator_roots = Map::new();
    validator_roots.insert("unit".to_owned(), json!({ "type": "null" }));
    for item in named {
        let root = contract_root(item, &contract_definitions)?;
        contract_definitions.insert(item.schema_name.to_owned(), root.clone());
        validator_roots.insert(item.schema_name.to_owned(), root);
    }
    let mut compiler = DescriptorCompiler::new(&contract_definitions);
    let type_validators = validator_roots
        .iter()
        .map(|(name, schema)| {
            compiler
                .compile_named(name, schema)
                .map(|index| (name.clone(), json!(index)))
        })
        .collect::<Result<Map<_, _>, _>>()?;
    write_json_const(&mut output, "VALIDATOR_TYPES", &compiler.pool)?;
    write_json_const(&mut output, "TYPE_VALIDATORS", &type_validators)?;
    let (requests, client_notifications, server_notifications) =
        method_validator_descriptors(&type_validators)?;
    for (name, value) in &[
        ("REQUEST_VALIDATORS", requests),
        ("CLIENT_NOTIFICATION_VALIDATORS", client_notifications),
        ("SERVER_NOTIFICATION_VALIDATORS", server_notifications),
    ] {
        write_json_const(&mut output, name, value)?;
    }
    output.push_str("export const WIRE_SCHEMAS = {\n");
    let mut wire_types = WireType::ALL.to_vec();
    wire_types.sort_by_key(|wire_type| wire_type.wire_name());
    for wire_type in wire_types {
        output.push_str(&format!(
            "  {:?}: {:?},\n",
            wire_type.wire_name(),
            wire_type.schema_name()
        ));
    }
    output.push_str("} as const;\n\nexport const METHOD_SPECS = [\n");
    for spec in METHOD_SPECS {
        output.push_str(&format!(
            "  {{ name: {:?}, direction: {:?}, kind: {:?}, clientToServerParamsType: {}, serverToClientParamsType: {}, resultType: {} }},\n",
            spec.name, direction_name(spec.direction), kind_name(spec.kind),
            option_wire_name(spec.client_to_server_params_type), option_wire_name(spec.server_to_client_params_type), option_wire_name(spec.result_type),
        ));
    }
    output.push_str("] as const;\n");
    Ok(output)
}

fn write_typescript_map(
    output: &mut String,
    name: &str,
    entry: impl Fn(&MethodSpec) -> Option<String>,
) {
    output.push_str(&format!("export interface {name} {{\n"));
    for spec in METHOD_SPECS {
        if let Some(value) = entry(spec) {
            output.push_str(&format!("  {:?}: {value};\n", spec.name));
        }
    }
    output.push_str("}\n\n");
}

fn write_json_const<T: serde::Serialize>(
    output: &mut String,
    name: &str,
    value: &T,
) -> Result<(), String> {
    output.push_str(&format!("export const {name} = "));
    output.push_str(&serde_json::to_string(value).map_err(|error| error.to_string())?);
    output.push_str(" as const;\n\n");
    Ok(())
}

type MethodValidatorDescriptors = (Map<String, Value>, Map<String, Value>, Map<String, Value>);

fn method_validator_descriptors(
    type_validators: &Map<String, Value>,
) -> Result<MethodValidatorDescriptors, String> {
    let index = |wire_type: WireType| -> Result<usize, String> {
        type_validators
            .get(wire_type.schema_name())
            .and_then(Value::as_u64)
            .map(|value| value as usize)
            .ok_or_else(|| format!("missing validator root: {}", wire_type.schema_name()))
    };
    let mut requests = Map::new();
    let mut client_notifications = Map::new();
    let mut server_notifications = Map::new();
    for spec in METHOD_SPECS {
        if spec.kind == MethodKind::Request {
            let params = spec.client_to_server_params_type.expect("request params");
            let result = spec.result_type.unwrap_or(WireType::Unit);
            requests.insert(
                spec.name.to_owned(),
                json!([index(params)?, index(result)?]),
            );
        } else {
            if let Some(params) = spec.client_to_server_params_type {
                client_notifications.insert(spec.name.to_owned(), json!(index(params)?));
            }
            if let Some(params) = spec.server_to_client_params_type {
                server_notifications.insert(spec.name.to_owned(), json!(index(params)?));
            }
        }
    }
    Ok((requests, client_notifications, server_notifications))
}

struct DescriptorCompiler<'a> {
    definitions: &'a Map<String, Value>,
    pool: Vec<Value>,
    interned: BTreeMap<String, usize>,
    named: BTreeMap<String, usize>,
}

impl<'a> DescriptorCompiler<'a> {
    fn new(definitions: &'a Map<String, Value>) -> Self {
        Self {
            definitions,
            pool: Vec::new(),
            interned: BTreeMap::new(),
            named: BTreeMap::new(),
        }
    }

    fn compile_named(&mut self, name: &str, schema: &Value) -> Result<usize, String> {
        if let Some(index) = self.named.get(name) {
            return Ok(*index);
        }
        let index = self.pool.len();
        self.pool.push(Value::Null);
        self.named.insert(name.to_owned(), index);
        let descriptor = self.descriptor(schema)?;
        self.pool[index] = descriptor.clone();
        self.interned
            .entry(serde_json::to_string(&descriptor).expect("descriptors serialize"))
            .or_insert(index);
        Ok(index)
    }

    fn compile(&mut self, schema: &Value) -> Result<usize, String> {
        if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
            let name = local_ref(reference)
                .map_err(|_| format!("unsupported validator reference: {reference}"))?;
            if let Some(index) = self.named.get(name) {
                return Ok(*index);
            }
            let target = self
                .definitions
                .get(name)
                .ok_or_else(|| format!("missing validator definition: {name}"))?
                .clone();
            return self.compile_named(name, &target);
        }
        let descriptor = self.descriptor(schema)?;
        Ok(self.intern(descriptor))
    }

    fn descriptor(&mut self, schema: &Value) -> Result<Value, String> {
        let object = schema
            .as_object()
            .ok_or_else(|| "boolean validator schemas are unsupported".to_owned())?;
        if let Some(value) = object.get("const") {
            return Ok(json!(["c", value]));
        }
        if let Some(Value::Array(values)) = object.get("enum") {
            let mut descriptor = vec![json!("e")];
            descriptor.extend(values.iter().cloned());
            return Ok(Value::Array(descriptor));
        }
        for key in ["oneOf", "anyOf", "allOf"] {
            if let Some(Value::Array(variants)) = object.get(key) {
                let opcode = if key == "allOf" { "l" } else { "u" };
                let mut descriptor = vec![json!(opcode)];
                for variant in variants {
                    descriptor.push(json!(self.compile(variant)?));
                }
                return Ok(Value::Array(descriptor));
            }
        }
        if let Some(Value::Array(types)) = object.get("type") {
            let mut descriptor = vec![json!("u")];
            for kind in types.iter().filter_map(Value::as_str) {
                let mut variant = object.clone();
                variant.insert("type".to_owned(), json!(kind));
                descriptor.push(json!(self.compile(&Value::Object(variant))?));
            }
            return Ok(Value::Array(descriptor));
        }
        match object.get("type").and_then(Value::as_str) {
            Some("null") => Ok(json!("z")),
            Some("boolean") => Ok(json!("b")),
            Some("integer") => Ok(constrained_descriptor("i", object, ["minimum", "maximum"])),
            Some("number") => Ok(constrained_descriptor("n", object, ["minimum", "maximum"])),
            Some("string") => Ok(constrained_descriptor(
                "s",
                object,
                ["pattern", "minLength", "maxLength"],
            )),
            Some("array") => {
                let item = object
                    .get("items")
                    .map(|schema| self.compile(schema))
                    .transpose()?
                    .unwrap_or_else(|| self.intern(json!("v")));
                Ok(with_optional_tail(
                    vec![json!("a"), json!(item)],
                    [
                        object.get("minItems").cloned(),
                        object.get("maxItems").cloned(),
                        object.get("uniqueItems").cloned(),
                    ],
                ))
            }
            Some("object") | None
                if object.contains_key("properties")
                    || object.contains_key("additionalProperties") =>
            {
                self.object_descriptor(object)
            }
            Some(_) | None => Ok(json!("v")),
        }
    }

    fn object_descriptor(&mut self, object: &Map<String, Value>) -> Result<Value, String> {
        let required = required_properties(object);
        let mut required_fields = Map::new();
        let mut optional_fields = Map::new();
        if let Some(properties) = object.get("properties").and_then(Value::as_object) {
            for (name, schema) in properties {
                let target = if required.contains(name.as_str()) {
                    &mut required_fields
                } else {
                    &mut optional_fields
                };
                target.insert(name.clone(), json!(self.compile(schema)?));
            }
        }
        let additional = match object.get("additionalProperties") {
            None | Some(Value::Bool(false)) => None,
            Some(Value::Bool(true)) => Some(self.intern(json!("v"))),
            Some(schema) => Some(self.compile(schema)?),
        };
        let property_names = object
            .get("propertyNames")
            .map(|schema| self.compile(schema))
            .transpose()?;
        Ok(with_optional_tail(
            vec![
                json!("o"),
                Value::Object(required_fields),
                Value::Object(optional_fields),
            ],
            [
                additional.map(|value| json!(value)),
                property_names.map(|value| json!(value)),
            ],
        ))
    }

    fn intern(&mut self, descriptor: Value) -> usize {
        let key = serde_json::to_string(&descriptor).expect("descriptors serialize");
        if let Some(index) = self.interned.get(&key) {
            return *index;
        }
        let index = self.pool.len();
        self.pool.push(descriptor);
        self.interned.insert(key, index);
        index
    }
}

fn with_optional_tail<const N: usize>(
    mut values: Vec<Value>,
    optional: [Option<Value>; N],
) -> Value {
    let mut tail = optional.map(|value| value.unwrap_or(Value::Null)).to_vec();
    while tail.last() == Some(&Value::Null) {
        tail.pop();
    }
    values.extend(tail);
    Value::Array(values)
}

fn constrained_descriptor<const N: usize>(
    opcode: &str,
    schema: &Map<String, Value>,
    constraints: [&str; N],
) -> Value {
    with_optional_tail(
        vec![json!(opcode)],
        constraints.map(|key| schema.get(key).cloned()),
    )
}

fn expand_type_refs(
    schema: &Value,
    definitions: &Map<String, Value>,
    exported: &BTreeMap<&str, &str>,
    preserve_exported: bool,
    stack: &mut BTreeSet<String>,
) -> Result<Value, String> {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let name = local_ref(reference)?;
        if preserve_exported {
            if let Some(ts_name) = exported.get(name) {
                return Ok(json!({ "x-typescript-ref": ts_name }));
            }
        }
        if !stack.insert(name.to_owned()) {
            return Ok(json!({ "x-typescript-ref": name }));
        }
        let target = definitions
            .get(name)
            .ok_or_else(|| format!("missing schema definition: {name}"))?;
        let expanded = expand_type_refs(target, definitions, exported, true, stack)?;
        stack.remove(name);
        return Ok(expanded);
    }
    let mut expanded = schema.clone();
    match &mut expanded {
        Value::Array(items) => {
            for item in items {
                *item = expand_type_refs(item, definitions, exported, true, stack)?;
            }
        }
        Value::Object(object) => {
            object.remove("$defs");
            for value in object.values_mut() {
                *value = expand_type_refs(value, definitions, exported, true, stack)?;
            }
        }
        _ => {}
    }
    Ok(expanded)
}

fn option_wire_name(value: Option<WireType>) -> String {
    value.map_or_else(
        || "null".to_owned(),
        |wire_type| format!("{:?}", wire_type.wire_name()),
    )
}

fn direction_name(direction: MethodDirection) -> &'static str {
    match direction {
        MethodDirection::ClientToServer => "clientToServer",
        MethodDirection::ServerToClient => "serverToClient",
        MethodDirection::Bidirectional => "bidirectional",
    }
}

fn kind_name(kind: MethodKind) -> &'static str {
    match kind {
        MethodKind::Request => "request",
        MethodKind::Notification => "notification",
    }
}

fn schema_to_typescript(schema: &Value) -> Result<String, String> {
    let object = schema
        .as_object()
        .ok_or_else(|| "boolean schemas are unsupported in TypeScript output".to_owned())?;
    if let Some(reference) = object.get("x-typescript-ref").and_then(Value::as_str) {
        return Ok(reference.to_owned());
    }
    if let Some(value) = object.get("const") {
        return Ok(json_literal(value));
    }
    if let Some(Value::Array(values)) = object.get("enum") {
        return Ok(values
            .iter()
            .map(json_literal)
            .collect::<Vec<_>>()
            .join(" | "));
    }
    for (union_key, separator) in [("oneOf", " | "), ("anyOf", " | "), ("allOf", " & ")] {
        if let Some(Value::Array(items)) = object.get(union_key) {
            return items
                .iter()
                .map(schema_to_typescript)
                .collect::<Result<Vec<_>, _>>()
                .map(|items| items.join(separator));
        }
    }
    match object.get("type") {
        Some(Value::Array(types)) => types
            .iter()
            .map(|value| {
                let mut variant = object.clone();
                variant.insert("type".to_owned(), value.clone());
                schema_to_typescript(&Value::Object(variant))
            })
            .collect::<Result<Vec<_>, _>>()
            .map(|types| types.join(" | ")),
        Some(Value::String(kind)) if kind == "object" => object_schema_to_typescript(object),
        Some(Value::String(kind)) if kind == "array" => {
            let items = object
                .get("items")
                .map(schema_to_typescript)
                .transpose()?
                .unwrap_or_else(|| "unknown".to_owned());
            Ok(format!("Array<{items}>"))
        }
        Some(Value::String(kind)) => Ok(primitive_ts(kind).to_owned()),
        None if object.contains_key("properties") => object_schema_to_typescript(object),
        None => Ok("unknown".to_owned()),
        _ => Err("invalid schema type".to_owned()),
    }
}

fn object_schema_to_typescript(object: &Map<String, Value>) -> Result<String, String> {
    let required = required_properties(object);
    let mut fields = Vec::new();
    if let Some(properties) = object.get("properties").and_then(Value::as_object) {
        for (name, schema) in properties {
            fields.push(format!(
                "{}{}: {}",
                ts_property(name),
                if required.contains(name.as_str()) {
                    ""
                } else {
                    "?"
                },
                schema_to_typescript(schema)?
            ));
        }
    }
    if let Some(additional) = object.get("additionalProperties") {
        if additional != &Value::Bool(false) {
            let value_type = if additional == &Value::Bool(true) {
                "unknown".to_owned()
            } else {
                schema_to_typescript(additional)?
            };
            fields.push(format!("[key: string]: {value_type}"));
        }
    }
    Ok(format!("{{ {} }}", fields.join("; ")))
}

fn required_properties(object: &Map<String, Value>) -> BTreeSet<&str> {
    object
        .get("required")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect()
}

fn primitive_ts(kind: &str) -> &'static str {
    match kind {
        "null" => "null",
        "boolean" => "boolean",
        "integer" | "number" => "number",
        "string" => "string",
        "object" => "Record<string, unknown>",
        "array" => "unknown[]",
        _ => "unknown",
    }
}

fn json_literal(value: &Value) -> String {
    serde_json::to_string(value).expect("JSON literals serialize")
}

fn ts_property(name: &str) -> String {
    if name.chars().enumerate().all(|(index, character)| {
        character == '_'
            || character == '$'
            || (character.is_ascii_alphanumeric() && (index > 0 || !character.is_ascii_digit()))
    }) {
        name.to_owned()
    } else {
        json_literal(&Value::String(name.to_owned()))
    }
}

